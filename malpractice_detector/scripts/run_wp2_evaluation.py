"""
run_wp2_evaluation.py
---------------------
Reproducible WP2 Evaluation, 16-Scenario Behavioral Scoring & Performance Benchmark Runner.

Executes real OpenCV + MediaPipe video processing (`process_video`) AND exercises
the RiskScorer engine and all 10 FastAPI backend handler paths directly (`api.py`) across
all 16 required academic evaluation scenarios:
  1. Normal examination (clean session)
  2. Brief head turn (< 0.4s - not sustained)
  3. Sustained head turn (>= 0.4s - sustained violation)
  4. Brief gaze deviation (< 0.7s - not sustained)
  5. Sustained gaze deviation (>= 0.7s - sustained violation)
  6. Candidate temporarily leaving frame (no_face >= 1.0s)
  7. Second person entering frame (multiple_faces)
  8. Reaching hands (intruder hand entering frame)
  9. Normal hand movement (candidate self hand suppressed by heuristic)
  10. Poor lighting (22% brightness perturbation robustness)
  11. Low resolution (160x120 scale robustness)
  12. No face detected (entire session blank/empty)
  13. Multiple simultaneous violations (compound scoring)
  14. Repeated brief violations (frequency rule: >= 2 occurrences in 10s window)
  15. Very short video (0.25s, edge-case guard)
  16. Long-duration video & 10-minute time normalization

Honesty note:
  No external multi-subject annotated proctoring dataset is bundled in this
  repository. Accuracy/Precision/Recall/F1/FPR/FNR below reflect ONLY the
  labeled synthetic & reference-frame scenarios generated by this script and
  must not be represented as wild-dataset model accuracy.

Output:
  malpractice_detector/results/wp2_evaluation_report.md
"""

